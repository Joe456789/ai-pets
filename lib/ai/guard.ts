// 注意事項第 33、34 點：不得呈現診斷、治療、處方或保證性結論。
// 這層是規則檢查，不依賴 AI 自律；命中時會要求重寫，仍命中就改用固定文字或交人工。
const BANNED: RegExp[] = [
  /保證.{0,6}(健康|康復|痊癒|沒病|安全|有效|不會)/,
  /(診斷|判斷)(為|出|結果)/,
  /確診/,
  /(得了|罹患|患有|可能是).{0,8}(病|症|炎|感染)/,
  /治癒|痊癒|根治|療效/,
  /處方/,
  /(可以|能|有助於?)預防.{0,8}(病|症|感染)/,
  /(吃|餵|服用|使用).{0,10}(藥|抗生素|止痛|驅蟲藥)/,
  /(不用|不需要|不必).{0,6}(看|找|帶.{0,4}看)?.{0,4}(獸醫|醫生|就醫)/,
  /一定(會好|沒事|沒問題)/,
];

export function findBannedClaim(text: string) {
  return BANNED.find((re) => re.test(text))?.source ?? null;
}
